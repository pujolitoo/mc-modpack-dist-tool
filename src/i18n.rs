//! Launcher languages.
//!
//! Texts live in `lang/<code>.json` (e.g. `lang/en.json`, `lang/es.json`):
//!
//! ```json
//! { "language_name": "Español", "texts": { "main.play": "JUGAR", "main.signed_as": "Sesión iniciada como {name}." } }
//! ```
//!
//! build.rs embeds every file of `lang/` in the executable (nothing is read from disk at runtime) and, at build time,
//! checks that every key used in the code exists in `en.json` and that `tf!` passes every placeholder the text uses.
//! To add a language, drop a new `lang/<code>.json` next to the others and rebuild: it shows up in the selector.
//! Missing texts in a translation fall back to English.
//!
//! In the code:
//!   - `t("main.play")` → `&'static str` in the current language;
//!   - `tf!("main.signed_as", name = name)` → `String`, replacing `{name}` (values are formatted with `Display`).

use serde_json::Value;
use std::collections::HashMap;
use std::fmt::Display;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::OnceLock;

// Generated by build.rs: `pub static LANGUAGE_FILES: &[(&str, &str)]` = (code, JSON contents), English first.
include!(concat!(env!("OUT_DIR"), "/languages.rs"));

/// The reference language: every key exists in it, and it is the fallback for missing translations.
pub const FALLBACK: &str = "en";

pub struct Language {
    /// Code taken from the file name (`es.json` → "es").
    pub code: &'static str,
    /// Name shown in the selector (`language_name`, written in the language itself).
    pub name: String,
    texts: HashMap<String, String>,
}

/// All embedded languages, parsed once. The fallback language is always the first one.
pub fn languages() -> &'static [Language] {
    static ALL: OnceLock<Vec<Language>> = OnceLock::new();
    ALL.get_or_init(|| {
        LANGUAGE_FILES
            .iter()
            .map(|(code, json)| {
                // build.rs already validated the files, so a parse error cannot happen in practice.
                let v: Value = serde_json::from_str(json).unwrap_or(Value::Null);
                let name = v.get("language_name").and_then(|n| n.as_str()).unwrap_or(code).to_string();
                let texts = v
                    .get("texts")
                    .and_then(|t| t.as_object())
                    .map(|o| o.iter().filter_map(|(k, v)| Some((k.clone(), v.as_str()?.to_string()))).collect())
                    .unwrap_or_default();
                Language { code, name, texts }
            })
            .collect()
    })
}

/// Index (in `languages()`) of the current language.
static CURRENT: AtomicUsize = AtomicUsize::new(0);

/// Changes the current language. Returns `false` (and changes nothing) if there is no language with that code.
pub fn set(code: &str) -> bool {
    match languages().iter().position(|l| l.code.eq_ignore_ascii_case(code.trim())) {
        Some(i) => {
            CURRENT.store(i, Ordering::Relaxed);
            true
        }
        None => false,
    }
}

pub fn current() -> &'static Language {
    let all = languages();
    &all[CURRENT.load(Ordering::Relaxed).min(all.len() - 1)]
}

/// Text for `key` in the current language (English if it is not translated; the key itself if it does not exist).
pub fn t(key: &'static str) -> &'static str {
    let all = languages();
    current()
        .texts
        .get(key)
        .or_else(|| all[0].texts.get(key))
        .map(|s| s.as_str())
        .unwrap_or(key)
}

/// Text for `key` with its `{name}` placeholders replaced (`{{` and `}}` are literal braces). Used by `tf!`.
pub fn fmt(key: &'static str, args: &[(&str, &dyn Display)]) -> String {
    let template = t(key);
    let mut out = String::with_capacity(template.len() + 16);
    let mut rest = template;
    while let Some(i) = rest.find(['{', '}']) {
        out.push_str(&rest[..i]);
        let tail = &rest[i..];
        if tail.starts_with("{{") || tail.starts_with("}}") {
            out.push_str(&tail[..1]);
            rest = &tail[2..];
        } else if let (true, Some(end)) = (tail.starts_with('{'), tail.find('}')) {
            let name = &tail[1..end];
            match args.iter().find(|(n, _)| *n == name) {
                Some((_, value)) => out.push_str(&value.to_string()),
                None => out.push_str(&tail[..=end]), // unknown placeholder: leave it visible
            }
            rest = &tail[end + 1..];
        } else {
            out.push_str(&tail[..1]);
            rest = &tail[1..];
        }
    }
    out.push_str(rest);
    out
}

/// `tf!("key", name = value, …)`: the text for `key` with each `{name}` replaced by `value`.
#[macro_export]
macro_rules! tf {
    ($key:literal $(, $name:ident = $val:expr)* $(,)?) => {
        $crate::i18n::fmt($key, &[$((stringify!($name), &$val as &dyn ::std::fmt::Display)),*])
    };
}
